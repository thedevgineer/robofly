from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from sim.topology import MOTOR_NAMES, Topology, build_default_topology


def q8_8(value: float) -> int:
    return int(np.clip(round(float(value) * 256.0), -32768, 32767))


def hex16(value: int) -> str:
    return f"{value & 0xFFFF:04x}"


def generate_chip(
    rtl_dir: Path = Path("rtl/generated"),
    mem_dir: Path = Path("rtl/mem"),
    tb_dir: Path = Path("tb"),
    seed: int = 1701,
) -> dict:
    topology = build_default_topology(seed=seed)
    rtl_dir.mkdir(parents=True, exist_ok=True)
    mem_dir.mkdir(parents=True, exist_ok=True)
    tb_dir.mkdir(parents=True, exist_ok=True)
    _write_memories(topology, mem_dir)
    files = {
        "core": rtl_dir / "robofly_core.sv",
        "tb": tb_dir / "robofly_core_tb.sv",
        "manifest": rtl_dir / "manifest.json",
    }
    files["core"].write_text(_core_sv(topology), encoding="utf-8")
    files["tb"].write_text(_tb_sv(topology), encoding="utf-8")
    manifest = {
        "neurons": topology.n,
        "synapses": topology.edge_count,
        "seed": seed,
        "fixed_point": "q8.8",
        "motors": list(MOTOR_NAMES),
        "files": {key: str(value) for key, value in files.items() if key != "manifest"},
    }
    files["manifest"].write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def _write_memories(topology: Topology, mem_dir: Path) -> None:
    (mem_dir / "pre.mem").write_text("\n".join(f"{int(v):04x}" for v in topology.pre) + "\n", encoding="utf-8")
    (mem_dir / "post.mem").write_text("\n".join(f"{int(v):04x}" for v in topology.post) + "\n", encoding="utf-8")
    (mem_dir / "weight_q8_8.mem").write_text(
        "\n".join(hex16(q8_8(v)) for v in topology.weight) + "\n",
        encoding="utf-8",
    )
    motor_index = np.zeros(topology.n, dtype=np.int16) - 1
    for idx, name in enumerate(MOTOR_NAMES):
        motor_index[topology.motors[name]] = idx
    (mem_dir / "motor_index.mem").write_text("\n".join(f"{int(v) & 0xFFFF:04x}" for v in motor_index) + "\n", encoding="utf-8")


def _core_sv(topology: Topology) -> str:
    return f"""// Generated by robofly-backend. Do not edit by hand.
// Datapath units. robofly_core schedules them once per tick.
module decay_add (
    input  logic signed [15:0] v_in,
    input  logic signed [15:0] drive,
    output logic signed [15:0] v_shift,
    output logic signed [15:0] v_out
);
    assign v_shift = v_in >>> 1;
    assign v_out = v_shift + drive;
endmodule

module spike_cmp (
    input  logic signed [15:0] v,
    output logic spike
);
    assign spike = (v > 16'sd256);
endmodule

module synapse_add (
    input  logic enable,
    input  logic signed [15:0] weight,
    input  logic signed [15:0] v_dst,
    output logic signed [15:0] v_out
);
    assign v_out = enable ? (v_dst + weight) : v_dst;
endmodule

module motor_inc (
    input  logic spike,
    input  logic index_ok,
    input  logic signed [31:0] accum,
    output logic signed [31:0] accum_out
);
    assign accum_out = (spike && index_ok) ? (accum + 32'sd1) : accum;
endmodule

module tick_ctrl #(
    parameter int N = 256,
    parameter int E = 1606
) (
    input  logic tick,
    input  logic rst,
    input  logic [31:0] cycle_count,
    output logic done,
    output logic [31:0] cycle_next
);
    assign done = tick && !rst;
    assign cycle_next = rst ? 32'd0 : cycle_count + N + E;
endmodule

module robofly_core #(
    parameter int N = {topology.n},
    parameter int E = {topology.edge_count},
    parameter int MOTOR_COUNT = {len(MOTOR_NAMES)}
) (
    input  logic clk,
    input  logic rst,
    input  logic tick,
    input  logic signed [15:0] drive [N],
    output logic done,
    output logic [N-1:0] spikes,
    output logic signed [31:0] motor_accum [MOTOR_COUNT],
    output logic [31:0] cycle_count
);
    logic signed [15:0] v [N];
    logic signed [15:0] pre_mem [E];
    logic signed [15:0] post_mem [E];
    logic signed [15:0] weight_mem [E];
    logic signed [15:0] motor_index [N];
    logic signed [15:0] v_rd, drive_rd, v_shift, v_sum;
    logic signed [15:0] pre_rd, post_rd, weight_rd, v_post_rd, v_post_sum;
    logic spike_bit, syn_en, motor_spike, motor_ok;
    logic signed [31:0] accum_rd, accum_sum;
    logic ctrl_done;
    logic [31:0] cycle_next;
    int i;
    int e;
    int dst;
    int src;
    int midx;

    decay_add u_decay(.v_in(v_rd), .drive(drive_rd), .v_shift(v_shift), .v_out(v_sum));
    spike_cmp u_cmp(.v(v_sum), .spike(spike_bit));
    synapse_add u_syn(.enable(syn_en), .weight(weight_rd), .v_dst(v_post_rd), .v_out(v_post_sum));
    motor_inc u_motor(.spike(motor_spike), .index_ok(motor_ok), .accum(accum_rd), .accum_out(accum_sum));
    tick_ctrl #(.N(N), .E(E)) u_ctrl(.tick(tick), .rst(rst), .cycle_count(cycle_count), .done(ctrl_done), .cycle_next(cycle_next));

    initial begin
        $readmemh("rtl/mem/pre.mem", pre_mem);
        $readmemh("rtl/mem/post.mem", post_mem);
        $readmemh("rtl/mem/weight_q8_8.mem", weight_mem);
        $readmemh("rtl/mem/motor_index.mem", motor_index);
    end

    always @(posedge clk) begin
        if (rst) begin
            done = 1'b0;
            cycle_count = 32'd0;
            spikes = '0;
            for (i = 0; i < N; i++) v[i] = 16'sd0;
            for (i = 0; i < MOTOR_COUNT; i++) motor_accum[i] = 32'sd0;
        end else begin
            done = 1'b0;
            if (tick) begin
                for (i = 0; i < MOTOR_COUNT; i++) motor_accum[i] = 32'sd0;
                for (i = 0; i < N; i++) begin
                    v_rd = v[i];
                    drive_rd = drive[i];
                    #0;
                    v[i] = v_sum;
                    spikes[i] = spike_bit;
                end
                for (e = 0; e < E; e++) begin
                    pre_rd = pre_mem[e];
                    post_rd = post_mem[e];
                    weight_rd = weight_mem[e];
                    src = pre_rd;
                    dst = post_rd;
                    syn_en = spikes[src];
                    v_post_rd = v[dst];
                    #0;
                    v[dst] = v_post_sum;
                end
                for (i = 0; i < N; i++) begin
                    midx = motor_index[i];
                    motor_ok = (midx >= 0 && midx < MOTOR_COUNT);
                    motor_spike = spikes[i];
                    accum_rd = motor_ok ? motor_accum[midx] : 32'sd0;
                    #0;
                    if (motor_ok) motor_accum[midx] = accum_sum;
                end
                cycle_count = cycle_next;
                done = ctrl_done;
            end
        end
    end
endmodule
"""


def _tb_sv(topology: Topology) -> str:
    drives = ", ".join("16'sd0" for _ in range(topology.n))
    return f"""// Generated smoke test for robofly_core.
`timescale 1ns/1ps
module robofly_core_tb;
    localparam int N = {topology.n};
    localparam int MOTOR_COUNT = {len(MOTOR_NAMES)};
    logic clk = 0;
    logic rst = 1;
    logic tick = 0;
    logic signed [15:0] drive [N];
    logic done;
    logic [N-1:0] spikes;
    logic signed [31:0] motor_accum [MOTOR_COUNT];
    logic [31:0] cycle_count;

    robofly_core dut(.clk(clk), .rst(rst), .tick(tick), .drive(drive), .done(done), .spikes(spikes), .motor_accum(motor_accum), .cycle_count(cycle_count));

    always #5 clk = ~clk;

    initial begin
        $dumpfile("tb/robofly_core_tb.vcd");
        $dumpvars(0, robofly_core_tb);
        for (int i = 0; i < N; i++) drive[i] = 16'sd0;
        #20 rst = 0;
        for (int j = 88; j < 96; j++) drive[j] = 16'sd512;
        repeat (5) begin
            tick = 1;
            #10 tick = 0;
            #10;
        end
        #50;
        $display("done=%0d cycles=%0d escape=%0d", done, cycle_count, motor_accum[5]);
        $finish;
    end
endmodule
"""
